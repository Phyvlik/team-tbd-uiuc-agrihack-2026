"""Extract CitrusFarm sequences (gt.csv + odom bag) and validate the B1 baseline.

Usage:  python scripts/validate_baseline.py [SEQ ...]

Writes:
  data/processed/<SEQ>/{reference,odom,...}.csv + meta.json
  results/baseline_validation.csv
  results/baseline_validation.md
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.baseline_validation import diagnose, speed_scale_ratio, validate_sequence, yaw_rate_gain  # noqa: E402
from src.data_loader import (CITRUSFARM_SEQUENCES, RAW_DIR, DataUnavailableError,  # noqa: E402
                             build_citrusfarm_sequence, save_processed)

RESULTS = ROOT / "results"


def main(seqs):
    RESULTS.mkdir(exist_ok=True)
    streams = {}
    for s in seqs:
        try:
            st = build_citrusfarm_sequence(s)
        except DataUnavailableError as e:
            print(f"[skip] {s}: {e}")
            continue
        save_processed(st)
        streams[s] = st
        print(f"[ok] extracted {s}: gt {len(st.reference)} rows, odom {len(st.odom)} rows")

    ratios = {s: speed_scale_ratio(st.reference, st.odom) for s, st in streams.items()}
    gains = {s: yaw_rate_gain(st.reference, st.odom) for s, st in streams.items()}

    all_rows, md = [], ["# Wheel-odometry baseline validation (computed)\n",
                        "Generated by `scripts/validate_baseline.py` from official CitrusFarm `gt.csv` + `odom_*.bag`.\n",
                        "Headline B1 = V2. D is a diagnostic that uses future data and must not be reported as a result.\n"]
    for s, st in streams.items():
        others = [ratios[o] for o in streams if o != s]
        loo = float(np.mean(others)) if others else None
        g_others = [gains[o] for o in streams if o != s and np.isfinite(gains[o])]
        loo_g = float(np.mean(g_others)) if g_others else None
        table, _ = validate_sequence(st.reference, st.odom, st.reference_lever_arm, loo, loo_g)
        table.insert(0, "sequence", s)
        table["speed_scale_ratio"] = ratios[s]
        table["yaw_rate_gain"] = gains[s]
        table["loo_scale_used"] = loo
        table["loo_yaw_gain_used"] = loo_g
        all_rows.append(table)
        md.append(f"\n## {s}\n")
        md.append(f"- distance {table['distance_m'].iloc[0]:.0f} m, duration {table['duration_s'].iloc[0]:.0f} s, "
                  f"wheel/RTK distance ratio {ratios[s]:.3f}, wheel yaw-rate gain {gains[s]:.3f}, "
                  f"oracle rotation {table.attrs['oracle_rotation_deg']:.1f} deg\n")
        md.append("\n| variant | mean m | RMSE m | max m | final m | final % dist |\n|---|---|---|---|---|---|\n")
        for _, r in table.iterrows():
            md.append(f"| {r.variant} | {r.mean_m:.2f} | {r.rmse_m:.2f} | {r.max_m:.2f} | {r.final_m:.2f} | "
                      f"{r.final_drift_pct_of_distance:.1f} |\n")
        for n in diagnose(table, ratios[s], gains[s]):
            md.append(f"- {n}\n")

    if all_rows:
        df = pd.concat(all_rows, ignore_index=True)
        df.to_csv(RESULTS / "baseline_validation.csv", index=False)
        (RESULTS / "baseline_validation.md").write_text("".join(md), encoding="utf-8")
        pd.set_option("display.width", 200)
        print(df[["sequence", "variant", "mean_m", "rmse_m", "max_m", "final_m", "speed_scale_ratio",
                  "yaw_rate_gain"]].round(2).to_string(index=False))


if __name__ == "__main__":
    main(sys.argv[1:] or [s for s in CITRUSFARM_SEQUENCES if (RAW_DIR / s / "gt.csv").exists()])
